export function getSifatExplanation(chipText) {
  const key = Object.keys(SIFAT_GLOSSARY).find((k) =>
    chipText.toLowerCase().includes(k.toLowerCase())
  );
  return key ? SIFAT_GLOSSARY[key] : 'Sifat pelafalan huruf menurut ilmu Tajwid.';
}

